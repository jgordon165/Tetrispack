#!/bin/sh
# Builds the SNES ROM with PVSnesLib.
#
#   consoles/snes/build.sh <work dir> [--data <folder with TETRIS.EXE>]
#
# Needs PVSNESLIB_HOME (consoles/snes/setup-pvsneslib.sh fetches it), Python 3,
# and the PC build's tetrispack_render_music (RENDER_MUSIC, default
# build/tetrispack_render_music) to write the soundtrack as Impulse Tracker
# modules and the sound effects as a module of samples.
#
# The ROM lands in <work dir>/tetrispack-snes.sfc. With --data its
# backgrounds are your TETRIS.EXE's: that ROM is for you only, don't share it.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../.." && pwd)
out=${1:?usage: build.sh <work dir> [--data <TETRIS folder>]}
shift
data=""
if [ "${1:-}" = "--data" ]; then data=${2:?--data needs a folder}; fi
: "${PVSNESLIB_HOME:?set PVSNESLIB_HOME to your PVSnesLib folder}"
render=${RENDER_MUSIC:-$root/build/tetrispack_render_music}
render=$(cd "$(dirname "$render")" && pwd)/$(basename "$render")   # absolute: it runs from res/

rm -rf "$out"
mkdir -p "$out/src" "$out/res"
out=$(cd "$out" && pwd)
cp "$here"/src/*.c "$root"/consoles/common/tetris_core.c "$root"/consoles/common/tetris_core.h "$out/src/"
cp "$here/data.asm" "$out/"
cp "$here/Makefile.in" "$out/Makefile"
if [ -n "$data" ]; then
    python3 -I "$root/tools/console_art.py" --console snes --out "$out" --data "$data"
else
    python3 -I "$root/tools/console_art.py" --console snes --out "$out"
fi
# The SNES has 64 KB of sound RAM for the driver, a song, its echo and the
# sound effects: each song plays once, then again a whole step up.
(cd "$out/res" && TETRISPACK_SNES_FORM=twice "$render" "$root/scripts" snes-it && "$render" "$root/scripts" sfx-it 8000)

cd "$out"
make musics
# SNESMOD splits a soundbank bigger than a 32 KB bank into SOUNDBANK__0, __1,
# ...; the game registers them highest first.
n=$(grep -c '^SOUNDBANK__[0-9]*:' res/soundbank.asm || true)
{
    echo "/* Generated by consoles/snes/build.sh. */"
    if [ "$n" -eq 0 ]; then
        echo "extern char SOUNDBANK__;"
        echo "#define SET_SOUNDBANKS() spcSetBank(&SOUNDBANK__)"
    else
        i=0; decl=""; calls=""
        while [ "$i" -lt "$n" ]; do
            decl="$decl extern char SOUNDBANK__$i;"
            calls="spcSetBank(&SOUNDBANK__$i); $calls"
            i=$((i + 1))
        done
        echo "$decl"
        echo "#define SET_SOUNDBANKS() do { $calls} while (0)"
    fi
} > soundbanks.h
make
cp tetrispack.sfc tetrispack-snes.sfc
echo "ROM: $out/tetrispack-snes.sfc ($(wc -c < tetrispack-snes.sfc) bytes)"
